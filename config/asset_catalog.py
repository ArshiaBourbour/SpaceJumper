#: The name given to the asset variant that ships with the game.  Files of the
#: default variant live directly in their part folder, without a variant level.
DEFAULT_VARIANT: str = "default"


class Anchor(Enum):
    """Where a sprite is pinned to its collision rectangle.

    Keeping the anchor explicit is what stops art from moving the collision
    body: a sprite is *drawn* relative to the rectangle, never the other way
    round.  A taller or wider sprite grows away from the anchor.
    """

    TOPLEFT = "topleft"
    CENTER = "center"
    BOTTOM_CENTER = "bottom_center"


# ---------------------------------------------------------------------------
# Player: parts, states and clips
# ---------------------------------------------------------------------------
@dataclass(frozen=True)
class PlayerPartSpec:
    """One layer of the player character."""

    #: Logical name, as used by ``PlayerSkin``.
    name: str
    #: Folder under ``assets/player`` its art lives in.
    folder: str
    #: Filename prefix, e.g. ``player_idle_01.png`` for the base layer.
    prefix: str
    #: Composition order; the base layer is drawn first, effects last.
    order: int


#: The layers a player is composed from, drawn in ``order``.  Only ``base``
#: ships with art today; the rest are drawn only when a skin supplies them, so
#: a future suit is a folder of PNGs and a one-line skin definition.
PLAYER_PARTS: tuple[PlayerPartSpec, ...] = (
    PlayerPartSpec("base", "base", "player", 0),
    PlayerPartSpec("suit", "suits", "suit", 1),
    PlayerPartSpec("helmet", "helmets", "helmet", 2),
    PlayerPartSpec("backpack", "backpacks", "backpack", 3),
    PlayerPartSpec("accessory", "accessories", "accessory", 4),
    PlayerPartSpec("effects", "effects", "effect", 5),
)

PLAYER_PART_BY_NAME: dict[str, PlayerPartSpec] = {
    part.name: part for part in PLAYER_PARTS
}

#: The default variant of every part: the art that ships with the game.
DEFAULT_SKIN_PARTS: dict[str, str] = {
    part.name: DEFAULT_VARIANT for part in PLAYER_PARTS
}


@dataclass(frozen=True)
class ClipSpec:
    """A player animation: how many frames it has and how fast it plays.

    ``frames`` is how many numbered files the state *may* have.  Missing frames
    are not an error: a state with no art of its own resolves up the
    ``fallback`` chain, so the architecture supports Idle / Jump / Fall /
    Landing / Hurt / Death while only Idle has to exist.
    """

    frames: int = 1
    #: Seconds each frame is shown for.  Timing is data, never a frame counter,
    #: so animation speed is identical at 30, 60, 120 and 144 FPS.
    frame_time: float = 0.2
    loop: bool = True
    #: State to borrow art from when this state has none of its own.
    fallback: str | None = "idle"


#: One entry per ``PlayerVisualState`` (keyed by its value).
PLAYER_CLIPS: dict[str, ClipSpec] = {
    "idle": ClipSpec(frames=1, frame_time=0.6, loop=True, fallback="idle"),
    "jump": ClipSpec(frames=1, frame_time=0.12, loop=False, fallback="idle"),
    "fall": ClipSpec(frames=1, frame_time=0.12, loop=False, fallback="idle"),
    "landing": ClipSpec(frames=1, frame_time=0.10, loop=False, fallback="idle"),
    "hurt": ClipSpec(frames=1, frame_time=0.10, loop=False, fallback="idle"),
    "death": ClipSpec(frames=1, frame_time=0.14, loop=False, fallback="idle"),
}

#: How long the Landing pose is held after touchdown, in seconds.  Landing is a
#: visual state only; it never delays a jump (the jump buffer still fires).
LANDING_HOLD: float = 0.10

#: Directions a sprite may face.  Mirroring is pre-computed and cached, so a
#: direction change never transforms an image inside the frame loop.
PLAYER_FACINGS: tuple[int, ...] = (1, -1)


def player_frame_path(
    state: str, *, part: str = "base", variant: str = DEFAULT_VARIANT, index: int = 1
) -> str:
    """Return the path of one player frame.

    Args:
        state: Clip name, e.g. ``"idle"``.
        part: Layer name from :data:`PLAYER_PARTS`.
        variant: Skin variant of that layer; ``"default"`` keeps the file in
            the part folder itself.
        index: 1-based frame number.
    """
    spec = PLAYER_PART_BY_NAME[part]
    folder = os.path.join(PLAYER_ASSETS_DIR, spec.folder)
    if variant != DEFAULT_VARIANT:
        folder = os.path.join(folder, variant)
    return os.path.join(folder, f"{spec.prefix}_{state}_{index:02d}.png")


