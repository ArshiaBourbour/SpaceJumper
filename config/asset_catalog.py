# Meteorites: visual variants
# ---------------------------------------------------------------------------
@dataclass(frozen=True)
class MeteorVariantSpec:
    """The look of one meteorite variant.

    Only the *sprite* size lives here.  The collision rectangle stays
    :data:`~config.constants.METEORITE_SIZE` for every variant, so choosing a
    look can never change how hard a hazard is to avoid.
    """

    name: str
    sprite_size: tuple[int, int]
    frames: int = 1
    frame_time: float = 0.12
    #: Whether the sprite is pre-rotated through a cycle of cached angles.
    spin: bool = False
    #: How many distinct rotations are pre-computed when ``spin`` is set.
    rotation_steps: int = 24


#: Visual variants the pipeline knows.  Gameplay still spawns
#: :data:`METEOR_DEFAULT_VARIANT` only; the rest exist so art can be dropped in
#: without touching the meteorite class.
METEOR_VARIANTS: dict[str, MeteorVariantSpec] = {
    "small": MeteorVariantSpec("small", (28, 28)),
    "medium": MeteorVariantSpec("medium", (40, 40)),
    "large": MeteorVariantSpec("large", (56, 56)),
    "burning": MeteorVariantSpec("burning", (40, 40)),
}

DEFAULT_METEOR_VARIANT: str = "medium"
#: Variant whose art is used when a variant has no art of its own.  Sizes
#: still come from the requested variant, so a missing file changes the
#: picture, never the footprint.
METEOR_ART_FALLBACK: str = "medium"


def meteor_frame_path(variant: str, index: int = 1) -> str:
    """Return the path of one meteorite frame."""
    return os.path.join(METEOR_ASSETS_DIR, f"meteor_{variant}_{index:02d}.png")


