@dataclass(frozen=True)
class ThemeSpec:
    """The dress of one world: backdrop art, backdrop colour, star colour.

    Gameplay never reads a background file path: it asks for a theme, and a
    theme without art falls back to a flat backdrop plus the starfield, which
    is exactly what the game shows today.
    """

    name: str
    #: Backdrop image, or ``None`` to paint :attr:`bg_color` instead.
    background: str | None = None
    bg_color: tuple[int, int, int] = BG_COLOR
    star_color: tuple[int, int, int] = STAR_COLOR
    #: Multiplier on the starfield's drift, so a "deep space" world can feel
    #: slower than a "clouds" one without touching the physics.
    star_drift_scale: float = 1.0


#: The worlds the pipeline can dress.  Only ``space`` is implemented; the rest
#: are the names the Art Bible reserves for later phases.
ENVIRONMENT_THEMES: dict[str, ThemeSpec] = {
    "space": ThemeSpec("space"),
    "earth": ThemeSpec("earth", background=None, bg_color=(20, 40, 70)),
    "moon": ThemeSpec("moon", background=None, bg_color=(18, 18, 26)),
    "mars": ThemeSpec("mars", background=None, bg_color=(60, 26, 20)),
}

DEFAULT_THEME: str = "space"


def theme_spec(name: str) -> ThemeSpec:
    """Return the theme named *name*, falling back to the default one."""
    return ENVIRONMENT_THEMES.get(name, ENVIRONMENT_THEMES[DEFAULT_THEME])


def background_path(theme: str) -> str:
    """Return the path of the backdrop art for *theme*."""
    return os.path.join(BACKGROUNDS_DIR, f"{theme}.png")


