"""The asset catalog: where every visual asset lives and what it looks like.

This module is the single source of truth for the asset **tree** and for the
visual specifications of the game's objects.  Nothing in the gameplay code
contains a file path or a sprite size any more: a caller asks the
:class:`~managers.asset_manager.AssetManager` for a *named* asset (``"idle"``,
``"large"``, ``"fragile"``) and the manager resolves it through the tables
below.

The catalog is deliberately three kinds of thing and no more:

* **Path builders** - how a logical name turns into a file.  The path of an
  asset is a pure function of its part, variant, state and frame number, so
  adding art is a matter of dropping a correctly named file into the tree, not
  of editing a lookup table.
* **Specifications** - the technical requirements from ``docs/ART_BIBLE.md``
  expressed as data: sprite sizes, frame counts, frame times, anchors, and the
  palette used when a look is generated by code instead of loaded from a file.
* **Themes** - how a world is dressed (background art, backdrop colour, star
  colour), so a future world is a configuration entry rather than a code path.

Everything here is plain data: no pygame, no I/O.  Whether a catalogued file
actually exists is the :class:`AssetManager`'s business, which is what lets the
game ship with placeholder art and still run.

Naming conventions (see ``docs/ART_BIBLE.md`` for the full rules)::

    assets/player/base/<variant>/player_<state>_<nn>.png
    assets/player/suits/<variant>/suit_<state>_<nn>.png
    assets/hazards/meteor/meteor_<variant>_<nn>.png
    assets/collectibles/fuel/fuel_<nn>.png
    assets/collectibles/powerups/powerup_<kind>_<nn>.png
    assets/environment/backgrounds/<theme>.png
    assets/environment/platforms/platform_<kind>.png
    assets/ui/<group>/<name>.png

``<variant>`` is omitted for the default variant, so the shipped base frame is
``assets/player/base/player_idle_01.png`` and a future Cyber suit would be
``assets/player/suits/cyber/suit_idle_01.png``.
"""

